# 2. Check available stock
@tool
def check_stock(item: str) -> str:
    """Check the current stock quantity of a product."""

    records = ws.get_all_records()

    for row in records:
        if str(row["product_name"]).lower() == item.lower():
            return f"{item}: {row['quantity']} units available."

    return f"{item} was not found in inventory."


# 3. Identify low-stock products
@tool
def check_low_stock(threshold: int = 10) -> str:
    """Find products whose stock is below or equal to the threshold."""

    records = ws.get_all_records()

    low = [
        f"{row['product_name']}: {row['quantity']} units"
        for row in records
        if int(row["quantity"]) <= threshold
    ]

    return "\n".join(low) if low else "No low-stock products found."


# 4. Check products nearing expiry
@tool
def check_expiry(days: int = 30) -> str:
    """Find products expiring within the specified number of days."""

    today = date.today()
    records = ws.get_all_records()
    expiring = []

    for row in records:
        try:
            expiry = date.fromisoformat(str(row["expiry_date"]))
            remaining = (expiry - today).days

            if 0 <= remaining <= days:
                expiring.append(
                    f"{row['product_name']} expires on {expiry}"
                )
        except (ValueError, TypeError):
            continue

    return "\n".join(expiring) if expiring else "No products nearing expiry."


