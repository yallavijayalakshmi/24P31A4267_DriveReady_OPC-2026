from pydantic import BaseModel, Field
from langchain.tools import tool
from datetime import date

# Product information is stored in Google Sheets (ws)

class RestockRequest(BaseModel):
    """A restocking request created by the kirana store owner."""

    product_name: str = Field(description="Name of the product")
    quantity: int = Field(description="Quantity to reorder", ge=1)
    supplier: str = Field(description="Supplier name")
    required_date: str = Field(description="Required delivery date")

@tool
def get_price(item: str, qty: int = 1) -> str:
    """Calculate the total price for a given quantity of a product."""

    if qty < 1:
        return "Quantity must be at least 1."

    inventory = ws.get_all_records()

    for product in inventory:
        if product["product_name"].lower().strip() == item.lower().strip():
            price = float(product["unit_price"])
            return f"{qty} x {item} = Rs {price * qty:.2f}"

    return f"{item} was not found in the inventory sheet."

@tool
def check_stock(item: str) -> str:
    """Check the available quantity of a product in the kirana store."""

    inventory = ws.get_all_records()

    for product in inventory:
        if product["product_name"].lower().strip() == item.lower().strip():
            return (
                f"Product: {item}\n"
                f"Available Stock: {product['quantity']}"
            )

    return f"{item} was not found in the inventory."

@tool
def check_low_stock(threshold: int = 10) -> str:
    """Identify products whose available quantity is at or below the threshold."""

    inventory = ws.get_all_records()

    low_stock = []

    for product in inventory:
        if int(product["quantity"]) <= threshold:
            low_stock.append(
                f"{product['product_name']}: {product['quantity']} units"
            )

    if not low_stock:
        return "No low-stock products found."

    return "Low-stock products:\n" + "\n".join(low_stock)

@tool
def check_expiry(days: int = 30) -> str:
    """Find products that will expire within the specified number of days."""

    inventory = ws.get_all_records()
    today = date.today()
    expiring = []

    for product in inventory:
        expiry = str(product.get("expiry_date", "")).strip()

        if not expiry:
            continue

        try:
            expiry_date = date.fromisoformat(expiry)

            if 0 <= (expiry_date - today).days <= days:
                expiring.append(
                    f"{product['product_name']}: expires on {expiry}"
                )
        except ValueError:
            continue

    if not expiring:
        return "No products nearing expiry found in the specified period."

    return "Products nearing expiry:\n" + "\n".join(expiring)

@tool
def log_restock_request(
    product_name: str,
    quantity: int,
    supplier: str,
    required_date: str
) -> str:
    """Record a restocking request after the store owner's approval."""

    try:
        request = RestockRequest(
            product_name=product_name,
            quantity=quantity,
            supplier=supplier,
            required_date=required_date
        )

        inventory = ws.get_all_records()

        exists = any(
            p["product_name"].lower().strip()
            == request.product_name.lower().strip()
            for p in inventory
        )

        if not exists:
            return f"{product_name} is not present in the inventory."

        restock_ws.append_row([
            request.product_name,
            request.quantity,
            request.supplier,
            request.required_date,
            "Pending"
        ])

        return (
            f"Restocking request recorded successfully!\n"
            f"Product: {request.product_name}\n"
            f"Quantity: {request.quantity}\n"
            f"Supplier: {request.supplier}\n"
            f"Status: Pending"
        )

    except Exception as e:
        return f"Could not record request: {e}"

