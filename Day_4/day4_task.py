from langchain.agents import create_agent

SYSTEM = """ROLE: You are DukaanMitra AI, a friendly and intelligent
business assistant for kirana store owners.

FACTS:
- Help manage kirana store inventory.
- Identify low-stock and near-expiry products.
- Calculate product prices.
- Help store owners manage restocking requests.
- Support supplier-related decisions.

RULES:
- Always use get_price for product prices.
- Always use check_stock for available stock.
- Always use check_low_stock to identify low-stock products.
- Always use check_expiry to identify products nearing expiry.
- Never invent inventory, price or supplier information.
- Before log_restock_request, collect product name, quantity,
  supplier and required date.
- Ask for explicit owner approval before recording a restocking request.
- Never claim that an actual supplier order has been placed.
- After recording, confirm the request details and status.

FORMAT:
Reply in under 100 words.
Use friendly, simple English or Telugu matching the store owner's language.
"""

agent = create_agent(
    model=llm,
    tools=[
        get_price,
        check_stock,
        check_low_stock,
        check_expiry,
        log_restock_request
    ],
    system_prompt=SYSTEM
)

history = []

def chat(text: str) -> str:
    global history

    try:
        result = agent.invoke({
            "messages": history + [
                {"role": "user", "content": text}
            ]
        })

        history = result["messages"]

        return history[-1].content

    except Exception as e:
        print("Agent error:", e)
        return "Sorry, DukaanMitra AI is temporarily unavailable. Please try again."


print(chat("Which products are running low in my store?"))

