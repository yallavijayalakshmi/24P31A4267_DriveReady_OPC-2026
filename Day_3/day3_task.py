import os
from google.colab import userdata
os.environ["GROQ_API_KEY"] = userdata.get("GROQ_API_KEY")   # LangChain reads it from here

from langchain_groq import ChatGroq
llm = ChatGroq(model="openai/gpt-oss-20b", temperature=0.3)

from langchain_core.prompts import ChatPromptTemplate, MessagesPlaceholder
from langchain_core.output_parsers import StrOutputParser

SYSTEM = """ROLE: You are DukaanMitra AI, a friendly and intelligent assistant
for small kirana store owners.

FACTS:
- Help store owners manage inventory and stock.
- Help analyse product sales and demand.
- Identify low-stock and near-expiry products.
- Suggest product restocking quantities.
- Help compare wholesale suppliers based on price,
  availability and delivery time.
- Use sample inventory and product information only when provided.

RULES:
- Never invent stock levels, sales figures or supplier details.
- Never guarantee supplier availability or delivery times without verified data.
- Never place an order without the store owner's approval.
- If required information is missing, say
  "Please provide the store details so I can help."
- Calculate totals carefully.

FORMAT:
Reply in under 100 words.
Use simple, friendly English or Telugu matching the store owner's language.
Give practical suggestions related to kirana business management."""

prompt = ChatPromptTemplate.from_messages([
    ("system", SYSTEM),
    MessagesPlaceholder("history"),
    ("human", "{question}"),
])

chain = prompt | llm | StrOutputParser()

history = []

def ask(question: str) -> str:
    answer = chain.invoke({
        "history": history,
        "question": question
    })

    history.extend([
        ("human", question),
        ("ai", answer)
    ])

    return answer


print(ask("Hi, can you help me manage my kirana store inventory?"))
print(ask("What services can you provide for my store?"))

import csv

def run_tests(path: str = "dukaanmitra_tests.csv") -> None:
    with open(path, newline="", encoding="utf-8") as file:
        rows = list(csv.DictReader(file))

    passed = 0

    for row in rows:
        answer = chain.invoke({
            "history": [],
            "question": row["question"]
        })

        ok = row["must_include"].lower() in answer.lower()
        passed += ok

        print(
            "PASS" if ok else "FAIL",
            "|",
            row["question"],
            "→",
            answer[:100]
        )

    total = len(rows)
    percentage = passed / total if total else 0

    print(f"\n{passed}/{total} passed ({percentage:.0%})")


run_tests()

